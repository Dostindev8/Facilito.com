// Builds the Login/Register background from the source photo: WebP (primary) + JPG (fallback) at the
// source's native resolution — never enlarged — plus a TS module with the intrinsic size.
// Usage: node scripts/build-login-bg.mjs [path/to/source.jpg]
import { mkdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const SRC = path.resolve(process.argv[2] ?? 'apps/web/brand-src/login-bg-source.jpg');
const OUT_DIR = path.resolve('apps/web/public/brand');
const META = path.resolve('apps/web/src/components/auth/login-bg.meta.ts');
const MAX_WIDTH = 2560;
const MIN_RECOMMENDED_WIDTH = 1920;
// Phones sit under a 50–90% white scrim; a lighter file keeps the image off the text-LCP critical path.
const SM_WIDTH = 820;

const source = sharp(SRC, { failOn: 'error' }).rotate();
const meta = await source.metadata();
const width = Math.min(meta.width, MAX_WIDTH);
const base = source.clone().resize({ width, withoutEnlargement: true }).toColourspace('srgb');

await mkdir(OUT_DIR, { recursive: true });
const webp = path.join(OUT_DIR, 'login-bg.webp');
const jpg = path.join(OUT_DIR, 'login-bg.jpg');
const webpSm = path.join(OUT_DIR, 'login-bg-sm.webp');
const webpInfo = await base.clone().webp({ quality: 88, effort: 6, smartSubsample: true }).toFile(webp);
await base.clone().jpeg({ quality: 88, mozjpeg: true, progressive: true }).toFile(jpg);
const smInfo = await source
  .clone()
  .resize({ width: Math.min(meta.width, SM_WIDTH), withoutEnlargement: true })
  .toColourspace('srgb')
  .webp({ quality: 80, effort: 6, smartSubsample: true })
  .toFile(webpSm);

await writeFile(
  META,
  `// Generated by scripts/build-login-bg.mjs — do not edit.\nexport const LOGIN_BG = { width: ${webpInfo.width}, height: ${webpInfo.height} } as const;\n`,
);

const kb = async (f) => `${((await stat(f)).size / 1024).toFixed(1)} KB`;
console.log(`source  ${meta.width}x${meta.height} ${meta.format} (${await kb(SRC)})`);
console.log(`webp    ${webpInfo.width}x${webpInfo.height} ${await kb(webp)}`);
console.log(`jpg     ${webpInfo.width}x${webpInfo.height} ${await kb(jpg)}`);
console.log(`webp-sm ${smInfo.width}x${smInfo.height} ${await kb(webpSm)}`);
if (meta.width < MIN_RECOMMENDED_WIDTH) {
  console.warn(`WARNING: source is ${meta.width}px wide; ${MIN_RECOMMENDED_WIDTH}px+ (ideally ${MAX_WIDTH}px) is needed for sharp results on large/retina screens. Not upscaled.`);
}
